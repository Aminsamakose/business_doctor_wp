<?php
/**
 * Thin wrapper around the Paystack API: initializing a transaction, verifying one, and checking a
 * webhook's signature. Holds no business logic of its own -- BD_Payments decides what to do with
 * what Paystack returns. Direct port of the HTTP shape in Samakose AI's psFetch()/paystackWebhook()
 * (src/services/finance.ts), adapted to WordPress's HTTP API.
 *
 * @package BusinessDoctor
 */

defined( 'ABSPATH' ) || exit;

class BD_Paystack {

	const API_BASE = 'https://api.paystack.co';

	/**
	 * The configured secret key, or empty if payments have not been set up.
	 *
	 * @return string
	 */
	public static function secret_key() {
		return (string) BD_Settings::get( 'paystack_secret_key' );
	}

	/**
	 * Whether a secret key has been saved at all.
	 *
	 * @return bool
	 */
	public static function is_configured() {
		return '' !== trim( self::secret_key() );
	}

	/**
	 * Whether the configured key looks like a live (not test) key. Paystack keys are always prefixed
	 * sk_live_ or sk_test_; this is a labelling aid for the admin screen only, never a security check.
	 *
	 * @return bool
	 */
	public static function is_live_key() {
		return 0 === strpos( self::secret_key(), 'sk_live_' );
	}

	/**
	 * A low-level call to the Paystack API.
	 *
	 * @param string $path   API path, e.g. '/transaction/initialize'.
	 * @param string $method HTTP method.
	 * @param array  $body   Request body for POST calls.
	 * @return array|WP_Error Decoded response body, or WP_Error.
	 */
	private static function request( $path, $method = 'GET', array $body = null ) {
		if ( ! self::is_configured() ) {
			return new WP_Error( 'bd_paystack_not_configured', __( 'Online payments are not configured yet.', 'business-doctor' ) );
		}
		$args = array(
			'method'  => $method,
			'timeout' => 20,
			'headers' => array(
				'Authorization' => 'Bearer ' . self::secret_key(),
				'Content-Type'  => 'application/json',
			),
		);
		if ( null !== $body ) {
			$args['body'] = wp_json_encode( $body );
		}
		$response = wp_remote_request( self::API_BASE . $path, $args );
		if ( is_wp_error( $response ) ) {
			return $response;
		}
		$code = wp_remote_retrieve_response_code( $response );
		$data = json_decode( (string) wp_remote_retrieve_body( $response ), true );
		if ( $code < 200 || $code >= 300 ) {
			$message = is_array( $data ) && ! empty( $data['message'] ) ? $data['message'] : __( 'The payment provider could not be reached.', 'business-doctor' );
			return new WP_Error( 'bd_paystack_provider_error', (string) $message, array(
				'status' => 502,
				'http'   => $code,
			) );
		}
		return is_array( $data ) ? $data : array();
	}

	/**
	 * Starts a transaction. Amount is in GHS (converted to pesewas, Paystack's smallest unit).
	 *
	 * @param string $email        Payer email.
	 * @param float  $amount_ghs   Amount in cedis.
	 * @param string $reference    Unique reference generated by BD_Payments.
	 * @param string $callback_url Where Paystack returns the payer after checkout.
	 * @param array  $metadata     Arbitrary metadata stored with the transaction.
	 * @return array|WP_Error
	 */
	public static function initialize( $email, $amount_ghs, $reference, $callback_url, array $metadata = array() ) {
		$result = self::request(
			'/transaction/initialize',
			'POST',
			array(
				'email'        => $email,
				'amount'       => (int) round( $amount_ghs * 100 ),
				'currency'     => 'GHS',
				'reference'    => $reference,
				'callback_url' => $callback_url,
				'metadata'     => $metadata,
			)
		);
		if ( is_wp_error( $result ) ) {
			return $result;
		}
		if ( empty( $result['data']['authorization_url'] ) ) {
			return new WP_Error( 'bd_paystack_provider_error', __( 'The payment provider did not return a payment page.', 'business-doctor' ), array( 'status' => 502 ) );
		}
		return $result['data'];
	}

	/**
	 * Verifies a transaction by reference.
	 *
	 * @param string $reference Transaction reference.
	 * @return array|WP_Error
	 */
	public static function verify( $reference ) {
		$result = self::request( '/transaction/verify/' . rawurlencode( $reference ) );
		if ( is_wp_error( $result ) ) {
			return $result;
		}
		return isset( $result['data'] ) ? $result['data'] : array();
	}

	/**
	 * Checks a webhook's X-Paystack-Signature header: HMAC-SHA512 of the raw request body, keyed with
	 * the secret key. Constant-time compare via hash_equals().
	 *
	 * @param string $raw_body  The exact, unparsed request body Paystack sent.
	 * @param string $signature The X-Paystack-Signature header value.
	 * @return bool
	 */
	public static function verify_signature( $raw_body, $signature ) {
		if ( ! self::is_configured() || empty( $signature ) ) {
			return false;
		}
		$expected = hash_hmac( 'sha512', (string) $raw_body, self::secret_key() );
		return hash_equals( $expected, (string) $signature );
	}
}
